"""Every citation key in the repo must be an entry of the verified bibliography.

Citations are written ``[key]`` or ``[key1, key2]`` with keys like
``mccormick1976computability`` (author, year, first title word); the README
links them as ``[McCormick 1976](#ref-key)`` into a generated References
section (``docs/readme_bib.py``). The
bibliography ``docs/references.bib`` is generated by ``docs/verify_refs.py``
from ``docs/refs.json``: DOI entries are checked against Crossref and their
BibTeX comes from Crossref, so a key found here is backed by a checked record.
"""

import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
KEY = r"[a-z][a-z-]*\d{4}[a-z0-9]*"
CITE = re.compile(rf"\[({KEY}(?:\s*[,;]\s*{KEY})*)\]|\(#ref-({KEY})\)")
SKIP = {".git", ".claude", ".venv", "node_modules", ".jax_cache", "__pycache__", ".ipynb_checkpoints"}


def bib_keys():
    return set(re.findall(r"^@\w+\{([^,\s]+),", (ROOT / "docs" / "references.bib").read_text(), re.M))


def sources():
    for p in ROOT.rglob("*"):
        if SKIP & set(p.relative_to(ROOT).parts) or not p.is_file():
            continue
        if p.suffix in (".py", ".md"):
            yield p, p.read_text(errors="ignore")
        elif p.suffix == ".ipynb":  # cell sources only, not outputs
            cells = json.loads(p.read_text()).get("cells", [])
            yield p, "\n".join("".join(c.get("source", "")) for c in cells)


def test_bib_matches_refs_json():
    """The .bib is in sync with its verified source list (rerun docs/verify_refs.py if not)."""
    refs = {r["key"] for r in json.loads((ROOT / "docs" / "refs.json").read_text())}
    assert bib_keys() == refs


def test_every_citation_is_in_the_bib():
    keys = bib_keys()
    missing = sorted(
        (str(p.relative_to(ROOT)), k)
        for p, text in sources()
        for m in CITE.finditer(text)
        for k in re.split(r"\s*[,;]\s*", m.group(1) or m.group(2))
        if k not in keys
    )
    assert not missing, f"citation keys not in docs/references.bib: {missing}"


def test_readme_links_resolve():
    """Every #ref-key link in the README has a References entry, and vice versa."""
    text = (ROOT / "README.md").read_text()
    links = set(re.findall(r"\(#ref-([^)\s]+)\)", text))
    anchors = set(re.findall(r'<a id="ref-([^"]+)"></a>', text))
    assert links == anchors, "rerun python docs/readme_bib.py"
